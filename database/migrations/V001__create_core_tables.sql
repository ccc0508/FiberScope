-- 植物纤维数据库：8张核心表、约束、索引与对象权限
-- 目标版本：PostgreSQL 18.x
-- 执行数据库：plant_fiber_db
-- 建议命令：psql -v ON_ERROR_STOP=1 -d plant_fiber_db -f V001__create_core_tables.sql
--
-- 本文件是一次性版本迁移，应在空的 fiber Schema 中执行。
-- 不使用 CREATE TABLE IF NOT EXISTS，目的是在重复执行或结构不一致时立即失败。

BEGIN;

SET LOCAL ROLE fiber_owner;
SET LOCAL search_path TO fiber, public;

DO $preflight$
BEGIN
    IF current_database() <> 'plant_fiber_db' THEN
        RAISE EXCEPTION
            '当前数据库为 %，本迁移只能在 plant_fiber_db 中执行',
            current_database();
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_namespace AS n
        JOIN pg_roles AS r
          ON r.oid = n.nspowner
        WHERE n.nspname = 'fiber'
          AND r.rolname = 'fiber_owner'
    ) THEN
        RAISE EXCEPTION
            'Schema fiber 不存在，或其所有者不是 fiber_owner';
    END IF;
END
$preflight$;

-- 1. 基础原料
CREATE TABLE fiber.material (
    material_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    material_code VARCHAR(16) NOT NULL,
    material_name VARCHAR(64) NOT NULL,

    CONSTRAINT pk_material
        PRIMARY KEY (material_id),
    CONSTRAINT uq_material_code
        UNIQUE (material_code),
    CONSTRAINT ck_material_code
        CHECK (material_code IN ('SW', 'HW'))
);

COMMENT ON TABLE fiber.material IS
    '基础原料：漂白针叶木浆（SW）和漂白阔叶木浆（HW）';

-- 2. 实验定义
CREATE TABLE fiber.experiment (
    experiment_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    experiment_code VARCHAR(32) NOT NULL,
    experiment_name VARCHAR(100) NOT NULL,
    experiment_type VARCHAR(16) NOT NULL,

    CONSTRAINT pk_experiment
        PRIMARY KEY (experiment_id),
    CONSTRAINT uq_experiment_code
        UNIQUE (experiment_code),
    CONSTRAINT ck_experiment_type
        CHECK (experiment_type IN ('beating', 'blend')),
    CONSTRAINT ck_experiment_code_type
        CHECK (
            (experiment_code IN ('SW_BEATING', 'HW_BEATING')
             AND experiment_type = 'beating')
            OR
            (experiment_code = 'BLEND'
             AND experiment_type = 'blend')
        )
);

COMMENT ON TABLE fiber.experiment IS
    '实验定义：针叶木打浆、阔叶木打浆和针阔复配';

-- 3. 全局唯一样本
CREATE TABLE fiber.sample (
    sample_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    canonical_code VARCHAR(32) NOT NULL,
    sample_type VARCHAR(16) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    notes TEXT,

    CONSTRAINT pk_sample
        PRIMARY KEY (sample_id),
    CONSTRAINT uq_sample_canonical_code
        UNIQUE (canonical_code),
    CONSTRAINT ck_sample_type
        CHECK (sample_type IN ('softwood', 'hardwood', 'blend')),
    CONSTRAINT ck_sample_canonical_code_format
        CHECK (
            (sample_type = 'softwood'
             AND canonical_code ~ '^SW_R[0-9]{5}$')
            OR
            (sample_type = 'hardwood'
             AND canonical_code ~ '^HW_R[0-9]{5}$')
            OR
            (sample_type = 'blend'
             AND canonical_code ~ '^BLEND_SW[0-9]{3}_HW[0-9]{3}$')
        )
);

COMMENT ON TABLE fiber.sample IS
    '全局唯一样本；复配端点复用对应纯浆样本，不创建副本';

-- 4. 数据来源行
CREATE TABLE fiber.data_source (
    source_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    file_name VARCHAR(255) NOT NULL,
    sheet_name VARCHAR(128) NOT NULL,
    source_row INTEGER NOT NULL,
    source_version VARCHAR(32) NOT NULL,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_data_source
        PRIMARY KEY (source_id),
    CONSTRAINT uq_data_source_location
        UNIQUE (file_name, sheet_name, source_row, source_version),
    CONSTRAINT ck_data_source_sheet
        CHECK (sheet_name = 'Sheet1'),
    CONSTRAINT ck_data_source_row
        CHECK (source_row >= 2),
    CONSTRAINT ck_data_source_official_file_version
        CHECK (
            (
                file_name IN (
                    '针叶木-打浆转数-打浆度(1).xlsx',
                    '针叶木-打浆转数-纤维特性(1).xlsx',
                    '针叶木-打浆转数-纸张性能(1).xlsx',
                    'data1-阔叶木-打浆转数-打浆度(1).xlsx',
                    'data2-阔叶木-打浆转数-纤维特性(1).xlsx',
                    'data3-阔叶木-打浆转数-纸张性能(1).xlsx'
                )
                AND source_version = '原始版'
            )
            OR
            (
                file_name IN (
                    'data4-针阔-复配-纤维特性0110(1).xlsx',
                    'data5-针阔-复配-纸张特性0110(1).xlsx'
                )
                AND source_version = '0110'
            )
        )
);

COMMENT ON TABLE fiber.data_source IS
    '正式来源文件中的数据行；旧复配版和数据汇总文件被数据库约束排除';

-- 5. 实验中的展示点
CREATE TABLE fiber.experiment_sample (
    experiment_id BIGINT NOT NULL,
    sample_id BIGINT NOT NULL,
    display_code VARCHAR(16) NOT NULL,
    display_order INTEGER NOT NULL,
    source_id BIGINT NOT NULL,

    CONSTRAINT pk_experiment_sample
        PRIMARY KEY (experiment_id, sample_id),
    CONSTRAINT uq_experiment_sample_display_code
        UNIQUE (experiment_id, display_code),
    CONSTRAINT uq_experiment_sample_display_order
        UNIQUE (experiment_id, display_order),
    CONSTRAINT ck_experiment_sample_display_order
        CHECK (display_order > 0),
    CONSTRAINT fk_experiment_sample_experiment
        FOREIGN KEY (experiment_id)
        REFERENCES fiber.experiment (experiment_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT fk_experiment_sample_sample
        FOREIGN KEY (sample_id)
        REFERENCES fiber.sample (sample_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT fk_experiment_sample_source
        FOREIGN KEY (source_id)
        REFERENCES fiber.data_source (source_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

COMMENT ON TABLE fiber.experiment_sample IS
    '样本在实验中的显示代码与顺序；同一样本可以出现在不同实验中';

-- 6. 样本原料组成和打浆条件
CREATE TABLE fiber.sample_component (
    sample_id BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    proportion_pct NUMERIC(5, 2) NOT NULL,
    beating_revolutions INTEGER NOT NULL,
    beating_degree_sr NUMERIC(5, 1) NOT NULL,
    source_id BIGINT NOT NULL,

    CONSTRAINT pk_sample_component
        PRIMARY KEY (sample_id, material_id),
    CONSTRAINT ck_sample_component_proportion
        CHECK (proportion_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_sample_component_revolutions
        CHECK (beating_revolutions >= 0),
    CONSTRAINT ck_sample_component_degree
        CHECK (beating_degree_sr BETWEEN 0 AND 100),
    CONSTRAINT fk_sample_component_sample
        FOREIGN KEY (sample_id)
        REFERENCES fiber.sample (sample_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT fk_sample_component_material
        FOREIGN KEY (material_id)
        REFERENCES fiber.material (material_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT fk_sample_component_source
        FOREIGN KEY (source_id)
        REFERENCES fiber.data_source (source_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

COMMENT ON TABLE fiber.sample_component IS
    '纯浆一个组分、复配样本两个组分；跨行合计和固定打浆条件由V002约束触发器检查';

-- 7. 十二项纤维特性
CREATE TABLE fiber.fiber_measurement (
    sample_id BIGINT NOT NULL,
    fiber_length_arithmetic_mm NUMERIC(10, 4),
    fiber_length_weighted_mm NUMERIC(10, 4),
    fiber_width_um NUMERIC(10, 3),
    fiber_coarseness_mg_m NUMERIC(12, 6),
    kink_angle_deg NUMERIC(8, 2),
    kinked_fiber_pct NUMERIC(8, 3),
    curved_fiber_pct NUMERIC(8, 3),
    fibrillation_length_pct NUMERIC(8, 3),
    broken_fiber_pct NUMERIC(8, 3),
    fines_length_pct NUMERIC(8, 3),
    fines_weighted_length_pct NUMERIC(8, 3),
    fines_area_pct NUMERIC(8, 3),
    source_id BIGINT NOT NULL,

    CONSTRAINT pk_fiber_measurement
        PRIMARY KEY (sample_id),
    CONSTRAINT ck_fiber_length_arithmetic
        CHECK (fiber_length_arithmetic_mm >= 0),
    CONSTRAINT ck_fiber_length_weighted
        CHECK (fiber_length_weighted_mm >= 0),
    CONSTRAINT ck_fiber_width
        CHECK (fiber_width_um >= 0),
    CONSTRAINT ck_fiber_coarseness
        CHECK (fiber_coarseness_mg_m >= 0),
    CONSTRAINT ck_fiber_kink_angle
        CHECK (kink_angle_deg BETWEEN 0 AND 180),
    CONSTRAINT ck_fiber_kinked_pct
        CHECK (kinked_fiber_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_fiber_curved_pct
        CHECK (curved_fiber_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_fiber_fibrillation_pct
        CHECK (fibrillation_length_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_fiber_broken_pct
        CHECK (broken_fiber_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_fiber_fines_length_pct
        CHECK (fines_length_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_fiber_fines_weighted_pct
        CHECK (fines_weighted_length_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_fiber_fines_area_pct
        CHECK (fines_area_pct BETWEEN 0 AND 100),
    CONSTRAINT fk_fiber_measurement_sample
        FOREIGN KEY (sample_id)
        REFERENCES fiber.sample (sample_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT fk_fiber_measurement_source
        FOREIGN KEY (source_id)
        REFERENCES fiber.data_source (source_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

COMMENT ON TABLE fiber.fiber_measurement IS
    '每个唯一样本最多一条纤维特性记录；十二项原始变量全部保留';

-- 8. 九项纸张性能及聚合说明
CREATE TABLE fiber.paper_measurement (
    sample_id BIGINT NOT NULL,
    basis_weight_g_m2 NUMERIC(10, 3),
    thickness_um NUMERIC(10, 3),
    burst_index NUMERIC(12, 4),
    tear_index NUMERIC(12, 4),
    tensile_index NUMERIC(12, 4),
    zero_span_tensile NUMERIC(12, 4),
    surface_roughness NUMERIC(12, 4),
    air_permeability NUMERIC(12, 4),
    folding_endurance_raw NUMERIC(12, 4),
    replicate_count SMALLINT NOT NULL DEFAULT 3,
    aggregation_method VARCHAR(64) NOT NULL
        DEFAULT '剔除偏差值后取最终均值',
    source_id BIGINT NOT NULL,

    CONSTRAINT pk_paper_measurement
        PRIMARY KEY (sample_id),
    CONSTRAINT ck_paper_basis_weight
        CHECK (basis_weight_g_m2 >= 0),
    CONSTRAINT ck_paper_thickness
        CHECK (thickness_um >= 0),
    CONSTRAINT ck_paper_burst_index
        CHECK (burst_index >= 0),
    CONSTRAINT ck_paper_tear_index
        CHECK (tear_index >= 0),
    CONSTRAINT ck_paper_tensile_index
        CHECK (tensile_index >= 0),
    CONSTRAINT ck_paper_zero_span
        CHECK (zero_span_tensile >= 0),
    CONSTRAINT ck_paper_surface_roughness
        CHECK (surface_roughness >= 0),
    CONSTRAINT ck_paper_air_permeability
        CHECK (air_permeability >= 0),
    CONSTRAINT ck_paper_folding_endurance
        CHECK (folding_endurance_raw >= 0),
    CONSTRAINT ck_paper_replicate_count
        CHECK (replicate_count = 3),
    CONSTRAINT ck_paper_aggregation_method
        CHECK (aggregation_method = '剔除偏差值后取最终均值'),
    CONSTRAINT fk_paper_measurement_sample
        FOREIGN KEY (sample_id)
        REFERENCES fiber.sample (sample_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT fk_paper_measurement_source
        FOREIGN KEY (source_id)
        REFERENCES fiber.data_source (source_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

COMMENT ON TABLE fiber.paper_measurement IS
    '每个唯一样本最多一条纸张性能最终均值记录；九项原始变量全部保留';
COMMENT ON COLUMN fiber.paper_measurement.air_permeability IS
    '透气度；设计暂定单位为 μm/(Pa·s)，源表未标注，待仪器或实验记录复核';
COMMENT ON COLUMN fiber.paper_measurement.folding_endurance_raw IS
    '耐折度原始值；单位待确认，确认前不换算、不重命名为特定物理量';

-- 外键和高频查询索引。主键与UNIQUE约束已经自动建立唯一索引。
CREATE INDEX ix_experiment_sample_sample
    ON fiber.experiment_sample (sample_id);
CREATE INDEX ix_experiment_sample_source
    ON fiber.experiment_sample (source_id);
CREATE INDEX ix_sample_component_material_revolutions
    ON fiber.sample_component (material_id, beating_revolutions);
CREATE INDEX ix_sample_component_source
    ON fiber.sample_component (source_id);
CREATE INDEX ix_fiber_measurement_source
    ON fiber.fiber_measurement (source_id);
CREATE INDEX ix_paper_measurement_source
    ON fiber.paper_measurement (source_id);

-- 当前对象权限：基础原料和实验定义由所有者维护；导入账号只修改实验数据。
-- 导入账号不授予DELETE/TRUNCATE，平台账号只读。
GRANT USAGE ON SCHEMA fiber
    TO fiber_importer, fiber_reader;

GRANT SELECT
    ON ALL TABLES IN SCHEMA fiber
    TO fiber_importer;

REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
    ON ALL TABLES IN SCHEMA fiber
    FROM fiber_importer;
GRANT INSERT, UPDATE
    ON fiber.sample,
       fiber.data_source,
       fiber.experiment_sample,
       fiber.sample_component,
       fiber.fiber_measurement,
       fiber.paper_measurement
    TO fiber_importer;

REVOKE ALL
    ON ALL SEQUENCES IN SCHEMA fiber
    FROM fiber_importer;
GRANT USAGE, SELECT
    ON SEQUENCE fiber.sample_sample_id_seq,
                fiber.data_source_source_id_seq
    TO fiber_importer;

GRANT SELECT
    ON ALL TABLES IN SCHEMA fiber
    TO fiber_reader;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
    ON ALL TABLES IN SCHEMA fiber
    FROM fiber_reader;

-- 未来对象的默认权限必须由对象创建者fiber_owner设置。
ALTER DEFAULT PRIVILEGES IN SCHEMA fiber
    GRANT SELECT, INSERT, UPDATE ON TABLES TO fiber_importer;
ALTER DEFAULT PRIVILEGES IN SCHEMA fiber
    GRANT USAGE, SELECT ON SEQUENCES TO fiber_importer;
ALTER DEFAULT PRIVILEGES IN SCHEMA fiber
    REVOKE DELETE, TRUNCATE, REFERENCES, TRIGGER
    ON TABLES FROM fiber_importer;

ALTER DEFAULT PRIVILEGES IN SCHEMA fiber
    GRANT SELECT ON TABLES TO fiber_reader;
ALTER DEFAULT PRIVILEGES IN SCHEMA fiber
    REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
    ON TABLES FROM fiber_reader;

COMMIT;
