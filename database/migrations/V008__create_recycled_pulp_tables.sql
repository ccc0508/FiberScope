\encoding UTF8
-- 再生纸浆循环回用实验：数据集、数据块和逐行观测表
-- 目标版本：PostgreSQL 18.x
-- 执行数据库：plant_fiber_db
--
-- 本迁移只新增对象，不修改原有8张核心表及其中的61个最终均值样本。

BEGIN;

SET LOCAL ROLE fiber_owner;
SET LOCAL search_path TO fiber, public;

DO $preflight$
BEGIN
    IF current_database() <> 'plant_fiber_db' THEN
        RAISE EXCEPTION
            '当前数据库为 %，本迁移只能在 plant_fiber_db 中执行',
            current_database();
    END IF;

    IF EXISTS (
        SELECT 1
        FROM information_schema.tables
        WHERE table_schema = 'fiber'
          AND table_name IN (
              'recycled_dataset',
              'recycled_data_block',
              'recycled_cycle_observation'
          )
    ) THEN
        RAISE EXCEPTION 'V008目标表已存在，请勿重复执行迁移';
    END IF;
END
$preflight$;

-- 1. 来源数据集。文件散列用于确认以后重新导入的是同一份工作簿。
CREATE TABLE fiber.recycled_dataset (
    dataset_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    dataset_code VARCHAR(32) NOT NULL,
    study_name VARCHAR(128) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    sheet_name VARCHAR(128) NOT NULL,
    source_version VARCHAR(32) NOT NULL,
    file_sha256 CHAR(64) NOT NULL,
    workbook_creator VARCHAR(100),
    workbook_last_modified_by VARCHAR(100),
    notes TEXT,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_recycled_dataset
        PRIMARY KEY (dataset_id),
    CONSTRAINT uq_recycled_dataset_code
        UNIQUE (dataset_code),
    CONSTRAINT uq_recycled_dataset_file_version
        UNIQUE (file_name, sheet_name, source_version, file_sha256),
    CONSTRAINT ck_recycled_dataset_sha256
        CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_recycled_dataset_sheet
        CHECK (sheet_name <> '')
);

COMMENT ON TABLE fiber.recycled_dataset IS
    '再生纸浆循环实验来源工作簿；使用SHA-256固定实际导入版本';

-- 2. 源表中可辨认的连续数据块。数据块不等同于已确认的实验处理条件。
CREATE TABLE fiber.recycled_data_block (
    block_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    dataset_id BIGINT NOT NULL,
    block_code VARCHAR(8) NOT NULL,
    block_name VARCHAR(32) NOT NULL,
    block_order SMALLINT NOT NULL,
    section_no SMALLINT NOT NULL,
    contributor_name VARCHAR(100),
    raw_material_grade VARCHAR(32),
    material_assignment_basis VARCHAR(128),
    condition_label VARCHAR(128),
    metadata_status VARCHAR(16) NOT NULL DEFAULT 'unknown',
    cycle_count SMALLINT NOT NULL,
    expected_replicates_per_cycle SMALLINT NOT NULL,
    source_start_row INTEGER NOT NULL,
    source_end_row INTEGER NOT NULL,
    notes TEXT,

    CONSTRAINT pk_recycled_data_block
        PRIMARY KEY (block_id),
    CONSTRAINT uq_recycled_block_id_dataset
        UNIQUE (block_id, dataset_id),
    CONSTRAINT uq_recycled_block_code
        UNIQUE (dataset_id, block_code),
    CONSTRAINT uq_recycled_block_order
        UNIQUE (dataset_id, block_order),
    CONSTRAINT ck_recycled_block_code
        CHECK (block_code ~ '^G[0-9]{2}$'),
    CONSTRAINT ck_recycled_block_name
        CHECK (block_name ~ '^数据块[0-9]{2}$'),
    CONSTRAINT ck_recycled_block_order
        CHECK (block_order > 0),
    CONSTRAINT ck_recycled_block_section
        CHECK (section_no > 0),
    CONSTRAINT ck_recycled_block_material
        CHECK (raw_material_grade IS NULL OR raw_material_grade IN ('美废12#', '美废13#')),
    CONSTRAINT ck_recycled_block_metadata_status
        CHECK (metadata_status IN ('known', 'unknown')),
    CONSTRAINT ck_recycled_block_metadata_consistency
        CHECK (
            (metadata_status = 'known' AND condition_label IS NOT NULL)
            OR (metadata_status = 'unknown' AND condition_label IS NULL)
        ),
    CONSTRAINT ck_recycled_block_cycle_count
        CHECK (cycle_count > 0),
    CONSTRAINT ck_recycled_block_replicates
        CHECK (expected_replicates_per_cycle > 0),
    CONSTRAINT ck_recycled_block_source_rows
        CHECK (source_start_row >= 2 AND source_end_row >= source_start_row),
    CONSTRAINT fk_recycled_block_dataset
        FOREIGN KEY (dataset_id)
        REFERENCES fiber.recycled_dataset (dataset_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

COMMENT ON TABLE fiber.recycled_data_block IS
    '数据汇总工作簿中的14个连续数据块；G01-G14是按源表位置生成的稳定编号，不代表14种已确认处理条件';
COMMENT ON COLUMN fiber.recycled_data_block.material_assignment_basis IS
    '原料牌号的判定依据，例如工作簿批注、黄色填充或同项目实验说明';
COMMENT ON COLUMN fiber.recycled_data_block.condition_label IS
    '正式实验条件名称；来源资料无法确认时保持NULL，不根据数值推测';
COMMENT ON COLUMN fiber.recycled_data_block.metadata_status IS
    'unknown表示正式实验条件无法确认；known表示condition_label已经由可靠实验记录确认';

-- 3. 逐行原始观测。原值不做平均、不做单位换算、不自动归一化。
CREATE TABLE fiber.recycled_cycle_observation (
    observation_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    dataset_id BIGINT NOT NULL,
    block_id BIGINT NOT NULL,
    cycle_no SMALLINT NOT NULL,
    replicate_no SMALLINT NOT NULL,
    source_row INTEGER NOT NULL,

    length_0_2_0_3_pct NUMERIC(18, 12) NOT NULL,
    length_0_3_0_45_pct NUMERIC(18, 12) NOT NULL,
    length_0_45_0_67_pct NUMERIC(18, 12) NOT NULL,
    length_0_67_1_pct NUMERIC(18, 12) NOT NULL,
    length_1_1_5_pct NUMERIC(18, 12) NOT NULL,
    length_1_5_2_24_pct NUMERIC(18, 12) NOT NULL,
    length_2_24_3_35_pct NUMERIC(18, 12) NOT NULL,
    length_3_35_5_01_pct NUMERIC(18, 12) NOT NULL,
    length_5_01_7_5_pct NUMERIC(18, 12) NOT NULL,
    length_gt_7_5_pct NUMERIC(18, 12) NOT NULL,

    fiber_length_arithmetic_mm NUMERIC(18, 12) NOT NULL,
    fiber_length_weighted_mm NUMERIC(18, 12) NOT NULL,
    fiber_width_um NUMERIC(18, 12) NOT NULL,
    fiber_coarseness_mg_m NUMERIC(18, 12) NOT NULL,
    kink_angle_deg NUMERIC(18, 12) NOT NULL,
    kinked_fiber_pct NUMERIC(18, 12) NOT NULL,
    curved_fiber_pct NUMERIC(18, 12) NOT NULL,
    fibrillation_length_pct NUMERIC(18, 12) NOT NULL,
    broken_fiber_pct NUMERIC(18, 12) NOT NULL,
    fines_length_pct NUMERIC(18, 12) NOT NULL,
    fines_weighted_length_pct NUMERIC(18, 12) NOT NULL,
    fines_area_pct NUMERIC(18, 12) NOT NULL,

    tensile_strength_kn_m NUMERIC(18, 12) NOT NULL,
    burst_strength_kpa NUMERIC(18, 12) NOT NULL,
    tear_strength_mn NUMERIC(18, 12) NOT NULL,

    CONSTRAINT pk_recycled_cycle_observation
        PRIMARY KEY (observation_id),
    CONSTRAINT uq_recycled_observation_source_row
        UNIQUE (dataset_id, source_row),
    CONSTRAINT uq_recycled_observation_replicate
        UNIQUE (block_id, cycle_no, replicate_no),
    CONSTRAINT ck_recycled_observation_cycle
        CHECK (cycle_no > 0),
    CONSTRAINT ck_recycled_observation_replicate_no
        CHECK (replicate_no > 0),
    CONSTRAINT ck_recycled_observation_source_row
        CHECK (source_row >= 2),
    CONSTRAINT ck_recycled_observation_length_distribution
        CHECK (
            length_0_2_0_3_pct BETWEEN 0 AND 100
            AND length_0_3_0_45_pct BETWEEN 0 AND 100
            AND length_0_45_0_67_pct BETWEEN 0 AND 100
            AND length_0_67_1_pct BETWEEN 0 AND 100
            AND length_1_1_5_pct BETWEEN 0 AND 100
            AND length_1_5_2_24_pct BETWEEN 0 AND 100
            AND length_2_24_3_35_pct BETWEEN 0 AND 100
            AND length_3_35_5_01_pct BETWEEN 0 AND 100
            AND length_5_01_7_5_pct BETWEEN 0 AND 100
            AND length_gt_7_5_pct BETWEEN 0 AND 100
        ),
    CONSTRAINT ck_recycled_observation_fiber_values
        CHECK (
            fiber_length_arithmetic_mm >= 0
            AND fiber_length_weighted_mm >= 0
            AND fiber_width_um >= 0
            AND fiber_coarseness_mg_m >= 0
            AND kink_angle_deg BETWEEN 0 AND 180
            AND kinked_fiber_pct BETWEEN 0 AND 100
            AND curved_fiber_pct BETWEEN 0 AND 100
            AND fibrillation_length_pct BETWEEN 0 AND 100
            AND broken_fiber_pct BETWEEN 0 AND 100
            AND fines_length_pct BETWEEN 0 AND 100
            AND fines_weighted_length_pct BETWEEN 0 AND 100
            AND fines_area_pct BETWEEN 0 AND 100
        ),
    CONSTRAINT ck_recycled_observation_paper_values
        CHECK (
            tensile_strength_kn_m >= 0
            AND burst_strength_kpa >= 0
            AND tear_strength_mn >= 0
        ),
    CONSTRAINT fk_recycled_observation_dataset
        FOREIGN KEY (dataset_id)
        REFERENCES fiber.recycled_dataset (dataset_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT fk_recycled_observation_block_dataset
        FOREIGN KEY (block_id, dataset_id)
        REFERENCES fiber.recycled_data_block (block_id, dataset_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

COMMENT ON TABLE fiber.recycled_cycle_observation IS
    '再生纸浆循环实验逐行观测；保留10档长度分布、12项纤维特性和3项纸张原始强度';
COMMENT ON COLUMN fiber.recycled_cycle_observation.replicate_no IS
    '同一数据块和循环次数内，按照源表行顺序生成的重复序号';
COMMENT ON COLUMN fiber.recycled_cycle_observation.tensile_strength_kn_m IS
    '抗张强度，单位kN/m；不是原核心表中的抗张指数';
COMMENT ON COLUMN fiber.recycled_cycle_observation.burst_strength_kpa IS
    '耐破强度，单位kPa；不是原核心表中的耐破指数';
COMMENT ON COLUMN fiber.recycled_cycle_observation.tear_strength_mn IS
    '撕裂强度，单位mN；不是原核心表中的撕裂指数';

CREATE INDEX ix_recycled_block_dataset
    ON fiber.recycled_data_block (dataset_id, section_no, block_order);
CREATE INDEX ix_recycled_observation_block_cycle
    ON fiber.recycled_cycle_observation (block_id, cycle_no, replicate_no);

-- 权限保持与原核心表一致：导入账号可增改但不可删，平台账号只读。
GRANT SELECT
    ON fiber.recycled_dataset,
       fiber.recycled_data_block,
       fiber.recycled_cycle_observation
    TO fiber_importer, fiber_reader;

REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
    ON fiber.recycled_dataset,
       fiber.recycled_data_block,
       fiber.recycled_cycle_observation
    FROM fiber_importer;

GRANT INSERT, UPDATE
    ON fiber.recycled_dataset,
       fiber.recycled_data_block,
       fiber.recycled_cycle_observation
    TO fiber_importer;

REVOKE ALL
    ON SEQUENCE fiber.recycled_dataset_dataset_id_seq,
                fiber.recycled_data_block_block_id_seq,
                fiber.recycled_cycle_observation_observation_id_seq
    FROM fiber_importer;

GRANT USAGE, SELECT
    ON SEQUENCE fiber.recycled_dataset_dataset_id_seq,
                fiber.recycled_data_block_block_id_seq,
                fiber.recycled_cycle_observation_observation_id_seq
    TO fiber_importer;

COMMIT;
